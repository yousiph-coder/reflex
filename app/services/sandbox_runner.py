"""
Ephemeral Docker sandbox runner for isolated patch validation.

Workflow
--------
1. Create a temporary working directory on the host.
2. Fetch the original file(s) from GitHub and write them to disk.
3. Apply each ``FilePatch`` (search-and-replace) to the file(s).
4. Write the generated unit test file.
5. Spin up an ephemeral Docker container from ``test_runner`` image
   with the working directory bind-mounted at ``/workspace``.
6. Execute the test command, capture stdout/stderr, enforce timeout.
7. Tear down the container and clean up temp files in a ``finally`` block.

Security constraints applied to every container:
- ``network_disabled=True`` — no outbound network access.
- ``mem_limit="512m"`` — hard memory cap.
- ``nano_cpus=1_000_000_000`` — 1 CPU core max.
- ``read_only=True`` on the root filesystem (workspace is a writable mount).
- ``user=1000`` — non-root.
- Auto-removed on exit.
"""

from __future__ import annotations

import asyncio
import logging
import os
import shutil
import tempfile
import time
from pathlib import Path
from typing import Any

from app.schemas.remediation import FilePatch, SandboxResult, UnitTestSpec

logger = logging.getLogger(__name__)

_DEFAULT_IMAGE = "autoheal-test-runner:latest"
_DEFAULT_TIMEOUT = 60  # seconds
_WORKSPACE_MOUNT = "/workspace"


class SandboxRunner:
    """Run remediation patches in an isolated Docker container.

    Usage::

        runner = SandboxRunner()
        result = await runner.validate_patch(
            file_patches=patches,
            unit_test=test_spec,
            original_files={"app/service.py": "<original source>"},
        )
    """

    def __init__(
        self,
        *,
        image: str = _DEFAULT_IMAGE,
        timeout: int = _DEFAULT_TIMEOUT,
        docker_base_url: str | None = None,
    ) -> None:
        self._image = image
        self._timeout = timeout
        self._docker_base_url = docker_base_url
        self._docker_client: Any = None

    def _get_docker_client(self) -> Any:
        """Lazily create the Docker client.

        Uses ``docker-py`` which is synchronous — all calls are wrapped
        with ``asyncio.to_thread()``.
        """
        if self._docker_client is None:
            import docker

            kwargs: dict[str, Any] = {}
            if self._docker_base_url:
                kwargs["base_url"] = self._docker_base_url
            else:
                kwargs["base_url"] = os.environ.get(
                    "DOCKER_HOST", "unix:///var/run/docker.sock"
                )
            self._docker_client = docker.from_env(**kwargs) if not self._docker_base_url else docker.DockerClient(**kwargs)
        return self._docker_client

    async def close(self) -> None:
        if self._docker_client is not None:
            try:
                await asyncio.to_thread(self._docker_client.close)
            except Exception:
                pass
            self._docker_client = None

    # ── Public API ──────────────────────────────────────────────

    async def validate_patch(
        self,
        *,
        file_patches: list[FilePatch],
        unit_test: UnitTestSpec,
        original_files: dict[str, str],
        extra_files: dict[str, str] | None = None,
        requirements: list[str] | None = None,
    ) -> SandboxResult:
        """Apply patches, write the test, and run it inside a container.

        Parameters
        ----------
        file_patches:
            Ordered list of search-and-replace patches.
        unit_test:
            Test file spec generated by the LLM.
        original_files:
            Mapping of ``{repo-relative path: file content}`` for
            every file referenced by the patches.
        extra_files:
            Optional additional files to write into the workspace
            (e.g. ``conftest.py``, ``__init__.py`` stubs).
        requirements:
            Optional extra pip packages to install before running tests.
        """
        workdir: Path | None = None
        container: Any = None
        start_time = time.monotonic()

        try:
            # ── 1. Prepare workspace ────────────────────────────
            workdir = Path(tempfile.mkdtemp(prefix="autoheal_sandbox_"))
            logger.debug("Sandbox workspace: %s", workdir)

            # Write original source files
            for rel_path, content in original_files.items():
                dest = workdir / rel_path
                dest.parent.mkdir(parents=True, exist_ok=True)
                dest.write_text(content, encoding="utf-8")

            # Write any extra files
            if extra_files:
                for rel_path, content in extra_files.items():
                    dest = workdir / rel_path
                    dest.parent.mkdir(parents=True, exist_ok=True)
                    dest.write_text(content, encoding="utf-8")

            # ── 2. Apply patches ────────────────────────────────
            for patch in file_patches:
                self._apply_patch(workdir, patch)

            # ── 3. Write unit test ──────────────────────────────
            test_dest = workdir / unit_test.test_file_path
            test_dest.parent.mkdir(parents=True, exist_ok=True)
            test_dest.write_text(unit_test.test_code, encoding="utf-8")

            # ── 4. Write requirements if any ────────────────────
            command_parts: list[str] = []
            if requirements:
                req_file = workdir / "_sandbox_requirements.txt"
                req_file.write_text("\n".join(requirements), encoding="utf-8")
                command_parts.append(
                    "pip install --quiet -r /workspace/_sandbox_requirements.txt &&"
                )
            command_parts.append(unit_test.test_command)
            full_command = " ".join(command_parts)

            # ── 5. Run container ────────────────────────────────
            container, stdout, stderr, exit_code, timed_out = (
                await self._run_container(workdir, full_command)
            )

            duration = time.monotonic() - start_time
            success = exit_code == 0 and not timed_out

            result = SandboxResult(
                success=success,
                exit_code=exit_code,
                stdout=stdout,
                stderr=stderr,
                duration_seconds=round(duration, 2),
                timed_out=timed_out,
                container_id=(
                    container.short_id if container else None
                ),
            )

            log_fn = logger.info if success else logger.warning
            log_fn(
                "Sandbox %s (exit=%d, timed_out=%s, %.1fs)",
                "PASSED" if success else "FAILED",
                exit_code,
                timed_out,
                duration,
            )
            return result

        except Exception as exc:
            duration = time.monotonic() - start_time
            logger.error("Sandbox execution error: %s", exc, exc_info=True)
            return SandboxResult(
                success=False,
                exit_code=-1,
                stdout="",
                stderr=f"Sandbox infrastructure error: {exc}",
                duration_seconds=round(duration, 2),
                timed_out=False,
            )

        finally:
            # ── 6. Clean up ─────────────────────────────────────
            if container is not None:
                await self._remove_container(container)
            if workdir and workdir.exists():
                try:
                    shutil.rmtree(workdir, ignore_errors=True)
                    logger.debug("Cleaned up workspace: %s", workdir)
                except Exception as exc:
                    logger.warning("Workspace cleanup failed: %s", exc)

    # ── Internal helpers ────────────────────────────────────────

    def _apply_patch(self, workdir: Path, patch: FilePatch) -> None:
        """Apply a single FilePatch to the workspace."""
        target = workdir / patch.file_path

        if patch.action.value == "create":
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(patch.replace_block, encoding="utf-8")
            logger.debug("Created file: %s", patch.file_path)
            return

        if patch.action.value == "delete":
            if target.exists():
                target.unlink()
                logger.debug("Deleted file: %s", patch.file_path)
            return

        # action == "modify"
        if not target.exists():
            raise FileNotFoundError(
                f"Patch target does not exist in workspace: {patch.file_path}"
            )

        original = target.read_text(encoding="utf-8")
        occurrences = original.count(patch.search_block)

        if occurrences == 0:
            raise ValueError(
                f"search_block not found in {patch.file_path}. "
                f"The LLM may have generated an inaccurate match.\n"
                f"--- Expected (first 200 chars) ---\n"
                f"{patch.search_block[:200]}"
            )
        if occurrences > 1:
            logger.warning(
                "search_block found %d times in %s; replacing first occurrence only",
                occurrences,
                patch.file_path,
            )

        patched = original.replace(patch.search_block, patch.replace_block, 1)
        target.write_text(patched, encoding="utf-8")
        logger.debug(
            "Patched %s (%d → %d bytes)",
            patch.file_path,
            len(original),
            len(patched),
        )

    async def _run_container(
        self,
        workdir: Path,
        command: str,
    ) -> tuple[Any, str, str, int, bool]:
        """Spin up an ephemeral container and run the command.

        Returns ``(container, stdout, stderr, exit_code, timed_out)``.
        """
        client = self._get_docker_client()
        timed_out = False

        # Convert Path to string for Docker bind mount
        host_path = str(workdir.resolve())

        # Create and start the container (detached)
        container = await asyncio.to_thread(
            client.containers.create,
            image=self._image,
            command=["sh", "-c", command],
            volumes={
                host_path: {
                    "bind": _WORKSPACE_MOUNT,
                    "mode": "rw",
                }
            },
            working_dir=_WORKSPACE_MOUNT,
            network_disabled=True,
            mem_limit="512m",
            nano_cpus=1_000_000_000,  # 1 CPU
            user="1000",
            detach=True,
            stdout=True,
            stderr=True,
            # Security options
            security_opt=["no-new-privileges:true"],
            # No capabilities
            cap_drop=["ALL"],
        )

        try:
            await asyncio.to_thread(container.start)
            logger.debug(
                "Container %s started (image=%s)",
                container.short_id,
                self._image,
            )

            # Wait for completion with timeout
            try:
                result = await asyncio.wait_for(
                    asyncio.to_thread(container.wait),
                    timeout=self._timeout,
                )
                exit_code = result.get("StatusCode", -1)
            except asyncio.TimeoutError:
                timed_out = True
                exit_code = -1
                logger.warning(
                    "Container %s timed out after %ds — killing",
                    container.short_id,
                    self._timeout,
                )
                try:
                    await asyncio.to_thread(container.kill)
                except Exception:
                    pass

            # Collect logs
            stdout_bytes = await asyncio.to_thread(
                container.logs, stdout=True, stderr=False,
            )
            stderr_bytes = await asyncio.to_thread(
                container.logs, stdout=False, stderr=True,
            )

            stdout = (
                stdout_bytes.decode("utf-8", errors="replace")
                if isinstance(stdout_bytes, bytes)
                else str(stdout_bytes)
            )
            stderr = (
                stderr_bytes.decode("utf-8", errors="replace")
                if isinstance(stderr_bytes, bytes)
                else str(stderr_bytes)
            )

            # Truncate excessively long output
            max_output = 50_000
            if len(stdout) > max_output:
                stdout = stdout[:max_output] + f"\n\n[truncated — {len(stdout)} total bytes]"
            if len(stderr) > max_output:
                stderr = stderr[:max_output] + f"\n\n[truncated — {len(stderr)} total bytes]"

            return container, stdout, stderr, exit_code, timed_out

        except Exception:
            # If anything goes wrong during execution, still return the container
            # so the finally block can clean it up
            try:
                await asyncio.to_thread(container.kill)
            except Exception:
                pass
            raise

    async def _remove_container(self, container: Any) -> None:
        """Force-remove a container, suppressing errors."""
        try:
            await asyncio.to_thread(
                container.remove, force=True, v=True,
            )
            logger.debug("Removed container %s", container.short_id)
        except Exception as exc:
            logger.warning(
                "Failed to remove container %s: %s",
                container.short_id,
                exc,
            )

    async def check_image_available(self) -> bool:
        """Verify that the sandbox Docker image exists locally."""
        try:
            client = self._get_docker_client()
            await asyncio.to_thread(client.images.get, self._image)
            return True
        except Exception:
            logger.warning(
                "Sandbox image '%s' not found. Build it with: "
                "docker build -t %s -f docker/test_runner.Dockerfile .",
                self._image,
                self._image,
            )
            return False
